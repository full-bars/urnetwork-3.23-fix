#!/usr/bin/env python3
"""Generate internal/brand/data.go from the finalized logo_data.json.

Run: python3 scripts/generate_terminal_logo.py /path/to/logo_data.json
"""
import json
import pathlib
import sys

source = json.loads(pathlib.Path(sys.argv[1]).read_text(encoding="utf-8"))
data = json.dumps(source["assets"], ensure_ascii=False, separators=(",", ":"))
target = pathlib.Path(__file__).resolve().parent.parent / "internal/brand/data.go"
target.write_text("// Code generated by scripts/generate_terminal_logo.py; DO NOT EDIT.\n"
                  "// Terminal art derived from the official ur.io files.\n"
                  "package brand\n\nconst assetJSON = `" + data + "`\n", encoding="utf-8")
