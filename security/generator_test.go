// the generator's range math is the part a feed cannot be trusted to get right:
// inputs arrive unsorted, adjacent and overlapping, and the reserved space must
// be removed without losing the remainder on either side
func TestMergeRangesSortsMergesAndJoinsAdjacent(t *testing.T) {
	got := mergeRanges([]iprange{
		{lo: 40, hi: 50},
		{lo: 10, hi: 20},
		{lo: 21, hi: 30},
		{lo: 15, hi: 25},
	})
	want := []iprange{{lo: 10, hi: 30}, {lo: 40, hi: 50}}
	if len(got) != len(want) {
		t.Fatalf("merged = %v, want %v", got, want)
	}
	for i := range want {
		if got[i] != want[i] {
			t.Fatalf("merged = %v, want %v", got, want)
		}
	}
}

func TestMergeRangesSingleAndEmpty(t *testing.T) {
	if got := mergeRanges(nil); len(got) != 0 {
		t.Fatalf("nil merged to %v", got)
	}
	if got := mergeRanges([]iprange{{lo: 7, hi: 7}}); len(got) != 1 || got[0].lo != 7 || got[0].hi != 7 {
		t.Fatalf("single = %v", got)
	}
}

func TestSubtractAllSplitsAroundReserved(t *testing.T) {
	got := subtractAll([]iprange{{lo: 100, hi: 200}}, []iprange{{lo: 150, hi: 160}})
	want := []iprange{{lo: 100, hi: 149}, {lo: 161, hi: 200}}
	if len(got) != len(want) {
		t.Fatalf("subtracted = %v, want %v", got, want)
	}
	for i := range want {
		if got[i] != want[i] {
			t.Fatalf("subtracted = %v, want %v", got, want)
		}
	}
}

func TestSubtractAllRemovesCoveredAndKeepsEdges(t *testing.T) {
	if got := subtractAll([]iprange{{lo: 10, hi: 20}}, []iprange{{lo: 0, hi: 30}}); len(got) != 0 {
		t.Fatalf("fully covered block survived as %v", got)
	}
	got := subtractAll([]iprange{{lo: 10, hi: 20}}, []iprange{{lo: 10, hi: 10}})
	if len(got) != 1 || got[0].lo != 11 || got[0].hi != 20 {
		t.Fatalf("edge subtraction = %v", got)
	}
}

// a csv feed that carries a CIDR row must be ingested, not counted as bad
func TestParseCSVAcceptsCidrRows(t *testing.T) {
	data := []byte("type,ip\nevil,203.0.113.0/24\nevil,198.51.100.7\nother,192.0.2.0/24\n")
	ranges, ranges6, host, bad := parseCSV(data, 1, 0, "evil")
	if len(ranges) != 2 || len(ranges6) != 0 || host != 2 || bad != 0 {
		t.Fatalf("ranges=%v v6=%v host=%d bad=%d", ranges, ranges6, host, bad)
	}
	if got := ranges[1]; got.lo != 0xc6336407 || got.hi != 0xc6336407 {
		t.Fatalf("plain address range = %#x-%#x", got.lo, got.hi)
	}
}

// overwriting a hand-written file would destroy source; a generated one is
// fair game, and -force is the documented override
func TestGuardOutputRefusesForeignFiles(t *testing.T) {
	dir := t.TempDir()
	foreign := filepath.Join(dir, "foreign.go")
	if err := os.WriteFile(foreign, []byte("package main\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := guardOutput(foreign, false); err == nil {
		t.Fatal("a file without the marker was not refused")
	}
	if err := guardOutput(foreign, true); err != nil {
		t.Fatalf("force was refused: %v", err)
	}
	generated := filepath.Join(dir, "generated.go")
	if err := os.WriteFile(generated, []byte("// Code generated by security. DO NOT EDIT.\npackage connect\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := guardOutput(generated, false); err != nil {
		t.Fatalf("a generated file was refused: %v", err)
	}
	if err := guardOutput(filepath.Join(dir, "missing.go"), false); err != nil {
		t.Fatalf("a new file was refused: %v", err)
	}
}
